// Copies the shared challenge files into firebase/functions/shared/ so the deployed function
// uses exactly the same schema, taxonomy, safety rules, validator and generation prompt as the
// seed pipeline. Runs before every deploy and every function test. The copy is git-ignored.
import { mkdirSync, copyFileSync, readFileSync, writeFileSync } from 'node:fs';

const from = new URL('../shared/', import.meta.url);
const to = new URL('../firebase/functions/shared/', import.meta.url);
mkdirSync(to, { recursive: true });
for (const f of ['challenge.schema.json', 'taxonomy.json', 'safety-rules.json', 'validate.mjs', 'generation-prompt.md']) {
  copyFileSync(new URL(f, from), new URL(f, to));
}
writeFileSync(new URL('README.txt', to), 'Generated by tools/sync-functions.mjs. Do not edit; edit ../../../../shared/ instead.\n');
console.log('Synced shared/ into firebase/functions/shared/');
